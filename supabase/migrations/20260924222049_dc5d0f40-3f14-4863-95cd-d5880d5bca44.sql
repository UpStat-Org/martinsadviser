CREATE TABLE public.service_orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  org_id uuid NOT NULL DEFAULT public.current_org_id()
    REFERENCES public.organizations(id) ON DELETE RESTRICT,
  client_id uuid NOT NULL REFERENCES public.clients(id) ON DELETE RESTRICT,
  service_id uuid REFERENCES public.services(id) ON DELETE SET NULL,
  title text NOT NULL CHECK (length(btrim(title)) > 0),
  description text,
  status text NOT NULL DEFAULT 'requested' CHECK (status IN (
    'requested', 'waiting_documents', 'preparing', 'submitted',
    'waiting_agency', 'approved', 'delivered', 'cancelled'
  )),
  priority text NOT NULL DEFAULT 'normal'
    CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
  assigned_to uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  due_date date,
  sla_hours integer CHECK (sla_hours IS NULL OR sla_hours > 0),
  quoted_amount numeric(12, 2) NOT NULL DEFAULT 0 CHECK (quoted_amount >= 0),
  external_cost numeric(12, 2) NOT NULL DEFAULT 0 CHECK (external_cost >= 0),
  currency text NOT NULL DEFAULT 'USD' CHECK (currency IN ('USD', 'BRL')),
  started_at timestamptz,
  submitted_at timestamptz,
  approved_at timestamptz,
  completed_at timestamptz,
  created_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX service_orders_org_status_idx ON public.service_orders(org_id, status);
CREATE INDEX service_orders_client_idx ON public.service_orders(client_id, created_at DESC);
CREATE INDEX service_orders_assigned_idx ON public.service_orders(assigned_to, status)
  WHERE assigned_to IS NOT NULL;
CREATE INDEX service_orders_due_idx ON public.service_orders(org_id, due_date)
  WHERE due_date IS NOT NULL AND status NOT IN ('delivered', 'cancelled');

CREATE TABLE public.service_order_permits (
  service_order_id uuid NOT NULL REFERENCES public.service_orders(id) ON DELETE CASCADE,
  permit_id uuid NOT NULL REFERENCES public.permits(id) ON DELETE RESTRICT,
  org_id uuid NOT NULL DEFAULT public.current_org_id()
    REFERENCES public.organizations(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (service_order_id, permit_id)
);

CREATE INDEX service_order_permits_permit_idx ON public.service_order_permits(permit_id);
CREATE INDEX service_order_permits_org_idx ON public.service_order_permits(org_id);

CREATE TABLE public.service_order_checklist_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  service_order_id uuid NOT NULL REFERENCES public.service_orders(id) ON DELETE CASCADE,
  org_id uuid NOT NULL DEFAULT public.current_org_id()
    REFERENCES public.organizations(id) ON DELETE RESTRICT,
  title text NOT NULL CHECK (length(btrim(title)) > 0),
  description text,
  document_type text,
  required boolean NOT NULL DEFAULT true,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN (
    'pending', 'received', 'approved', 'rejected', 'not_applicable'
  )),
  document_path text,
  file_name text,
  rejection_reason text,
  due_date date,
  sort_order integer NOT NULL DEFAULT 0,
  completed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  completed_at timestamptz,
  created_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX service_order_checklist_order_idx
  ON public.service_order_checklist_items(service_order_id, sort_order, created_at);
CREATE INDEX service_order_checklist_org_status_idx
  ON public.service_order_checklist_items(org_id, status);

CREATE TABLE public.service_order_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  service_order_id uuid NOT NULL REFERENCES public.service_orders(id) ON DELETE CASCADE,
  org_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
  event_type text NOT NULL CHECK (event_type IN (
    'created', 'status_changed', 'assignment_changed', 'due_date_changed',
    'checklist_changed', 'permit_linked', 'permit_unlinked', 'note'
  )),
  from_value text,
  to_value text,
  note text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX service_order_events_order_idx
  ON public.service_order_events(service_order_id, created_at DESC);
CREATE INDEX service_order_events_org_idx ON public.service_order_events(org_id);


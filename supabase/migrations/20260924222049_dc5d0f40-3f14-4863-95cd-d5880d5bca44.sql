CREATE OR REPLACE FUNCTION public.validate_service_order_scope()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.clients c
    WHERE c.id = NEW.client_id AND c.org_id = NEW.org_id
  ) THEN
    RAISE EXCEPTION 'client must belong to the service order organization';
  END IF;

  IF NEW.service_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.services s
    WHERE s.id = NEW.service_id AND s.org_id = NEW.org_id
  ) THEN
    RAISE EXCEPTION 'service must belong to the service order organization';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER validate_service_order_scope_trigger
  BEFORE INSERT OR UPDATE OF org_id, client_id, service_id ON public.service_orders
  FOR EACH ROW EXECUTE FUNCTION public.validate_service_order_scope();

CREATE OR REPLACE FUNCTION public.validate_service_order_child_scope()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  order_org uuid;
BEGIN
  SELECT org_id INTO order_org
  FROM public.service_orders
  WHERE id = NEW.service_order_id;

  IF order_org IS NULL OR order_org <> NEW.org_id THEN
    RAISE EXCEPTION 'service order child must belong to the order organization';
  END IF;

  IF TG_TABLE_NAME = 'service_order_permits' AND NOT EXISTS (
    SELECT 1 FROM public.permits p
    WHERE p.id = NEW.permit_id AND p.org_id = NEW.org_id
  ) THEN
    RAISE EXCEPTION 'permit must belong to the service order organization';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER validate_service_order_permit_scope_trigger
  BEFORE INSERT OR UPDATE ON public.service_order_permits
  FOR EACH ROW EXECUTE FUNCTION public.validate_service_order_child_scope();

CREATE TRIGGER validate_service_order_checklist_scope_trigger
  BEFORE INSERT OR UPDATE OF org_id, service_order_id ON public.service_order_checklist_items
  FOR EACH ROW EXECUTE FUNCTION public.validate_service_order_child_scope();

CREATE OR REPLACE FUNCTION public.validate_task_service_order_scope()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.service_order_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.service_orders so
    WHERE so.id = NEW.service_order_id
      AND so.org_id = NEW.org_id
      AND (NEW.client_id IS NULL OR so.client_id = NEW.client_id)
  ) THEN
    RAISE EXCEPTION 'task must belong to the service order organization and client';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER validate_task_service_order_scope_trigger
  BEFORE INSERT OR UPDATE OF org_id, client_id, service_order_id ON public.tasks
  FOR EACH ROW EXECUTE FUNCTION public.validate_task_service_order_scope();

CREATE OR REPLACE FUNCTION public.apply_service_order_milestones()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NEW.status = 'preparing' AND NEW.started_at IS NULL THEN
      NEW.started_at := now();
    ELSIF NEW.status = 'submitted' AND NEW.submitted_at IS NULL THEN
      NEW.submitted_at := now();
    ELSIF NEW.status = 'approved' AND NEW.approved_at IS NULL THEN
      NEW.approved_at := now();
    ELSIF NEW.status = 'delivered' AND NEW.completed_at IS NULL THEN
      NEW.completed_at := now();
    ELSIF OLD.status = 'delivered' AND NEW.status <> 'delivered' THEN
      NEW.completed_at := NULL;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER apply_service_order_milestones_trigger
  BEFORE UPDATE OF status ON public.service_orders
  FOR EACH ROW EXECUTE FUNCTION public.apply_service_order_milestones();

